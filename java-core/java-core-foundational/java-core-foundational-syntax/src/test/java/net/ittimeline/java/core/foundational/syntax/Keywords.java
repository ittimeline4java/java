public class Keywords {
    public static void main(String[] args) {
        //将特殊值true赋值给布尔类型的变量flag
        boolean flag = true;
        //字符串拼接打印输出变量flag存储的值
        System.out.println("1.flag = " + flag);
        //修改变量flag的值为特殊值false
        flag = false;
        System.out.println("2.flag = " + flag);

        //将特殊值null赋值给String类型的变量str
        String str = null;
        //字符串拼接打印输出变量str存储的值
        System.out.println("3.str = " + str);

    }
}
