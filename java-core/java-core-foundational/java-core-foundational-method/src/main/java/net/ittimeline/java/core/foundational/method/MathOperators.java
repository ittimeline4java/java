public class MathOperators {


    /**
     * 定义一个有参有返回值静态方法
     * 实现两个整数相加
     *
     * @param left  第一个整数
     * @param right 第二个整数
     * @return 两个整数相加的和
     */
    public static long sum(int left, int right) {
        return left + right;
    }
}
